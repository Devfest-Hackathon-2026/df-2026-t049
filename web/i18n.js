export function formatLeagueTime(milliseconds) {
 if(!Number.isFinite(milliseconds)) return '—';
 const date=new Date(milliseconds);if(!Number.isFinite(date.getTime()))return '—';
 const format=timeZone=>new Intl.DateTimeFormat(locale,{timeZone,year:'numeric',month:'2-digit',day:'2-digit',hour:'2-digit',minute:'2-digit',hourCycle:'h23'}).format(date);
 return `${format('Asia/Tokyo')} JST (${format('UTC')} UTC)`;
}
