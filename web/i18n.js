const storageKey = 'reliefroute.language';
export function detectLocale(languages) {
  for (const language of languages) {
    const base = String(language).toLowerCase().split(/[-_]/)[0];
    if (Object.hasOwn(messages, base)) return base;
  }
  return 'en';
}
let locale = 'ja';
try { const saved = localStorage.getItem(storageKey); if (Object.hasOwn(messages, saved)) locale = saved; } catch { /* Storage may be unavailable in private mode. */ }
export function getLocale() { return locale; }
export function setLocale(value) {
  if (!Object.hasOwn(messages, value)) return;
  locale = value;
  try { localStorage.setItem(storageKey, locale); } catch { /* In-memory switching still works. */ }
}
export function t(key, values = {}) {
  const variant = locale === 'en' && values.count === 1 && messages.en[key + 'One'] ? key + 'One' : key;
  const message = messages[locale][variant] ?? messages.zh[variant] ?? variant;
  return message.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}
export function applyTranslations() {
  document.documentElement.lang = {zh: 'zh-CN', ja: 'ja', en: 'en'}[locale];
  for (const node of document.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const attr of ['aria-label', 'title', 'content']) {
    for (const node of document.querySelectorAll(`[data-i18n-${attr}]`)) node.setAttribute(attr, t(node.getAttribute(`data-i18n-${attr}`)));
  }
  document.title = t('title');
  document.querySelector('#language').value = locale;
}

